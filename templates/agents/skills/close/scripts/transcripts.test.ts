// transcripts.test.ts — peer of transcripts.ts: the user's own turns from Claude
// Code's and Codex's session files, what is dropped, which record wins, and that
// corrections.ts hands a non-T3 session to it.
//
// Run: node --test --experimental-strip-types .agents/skills/close/scripts/transcripts.test.ts
//
// A throwaway HOME, Claude config dir and Codex home; no T3 database; TZ pinned
// to UTC; every harness session variable absent unless a case sets one. The
// cases run in order and share the fixtures.

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, realpathSync, rmSync, utimesSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, test } from "node:test";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SUT = join(HERE, "transcripts.ts");
const TMP = realpathSync(mkdtempSync(join(tmpdir(), "transcripts-test-")));
after(() => rmSync(TMP, { recursive: true, force: true }));

const CLAUDE = join(TMP, "claude");
const CODEX = join(TMP, "codex");
const BASE: Record<string, string> = {
  PATH: process.env.PATH ?? "",
  TZ: "UTC",
  HOME: join(TMP, "home"),
  T3CODE_HOME: join(TMP, "no-t3"),
  CLAUDE_CONFIG_DIR: CLAUDE,
  CODEX_HOME: CODEX,
};
mkdirSync(BASE.HOME as string, { recursive: true });

const W = join(TMP, "shop");
spawnSync("git", ["init", "-q", W]);

function run(args: string[] = [], env: Record<string, string> = {}, script = SUT): { rc: number | null; out: string; err: string } {
  const r = spawnSync(process.execPath, ["--no-warnings", "--experimental-strip-types", script, ...args], {
    cwd: W,
    encoding: "utf8",
    env: { ...BASE, ...env },
  });
  return { rc: r.status, out: r.stdout.replace(/\n+$/, ""), err: r.stderr };
}

test("no record anywhere: exit 2, and says so", () => {
  const r = run();
  assert.equal(r.rc, 2);
  assert.ok(r.err.includes("no record of this session"), r.err);
});

