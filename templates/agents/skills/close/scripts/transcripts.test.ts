const jsonl = (rows: unknown[]): string => `${rows.map((r) => JSON.stringify(r)).join("\n")}\n`;

test("claude: typed turns, reminders stripped, invocations and tool output dropped", () => {
  const dir = join(CLAUDE, "projects", W.replace(/[^A-Za-z0-9]/g, "-"));
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "sess-1.jsonl"), jsonl(CLAUDE_SESSION));
  const r = run();
  assert.equal(
    r.out,
    [
      "09:00\tAdd a retry to checkout.",
      "09:03\tNo, retry once, not three times.",
      "09:04\t/close but first say why the push failed",
      '09:05\t[answered] "Which store?"="Postgres"',
    ].join("\n"),
  );
  assert.ok(r.err.includes("source claude"), "…names its source");
  assert.equal(
    run(["--full"]).out.split("\n")[1],
    "09:03\tNo, retry once, not three times.\\nThe processor bills each attempt.",
    "--full keeps the whole turn, newlines escaped",
  );
});

test("claude: the session id picks the transcript", () => {
  mkdirSync(join(CLAUDE, "projects/-elsewhere"), { recursive: true });
  writeFileSync(
    join(CLAUDE, "projects/-elsewhere/abc-123.jsonl"),
    jsonl([{ type: "user", timestamp: "2026-01-12T10:00:00.000Z", message: { role: "user", content: "from the id" } }]),
  );
  assert.equal(run([], { CLAUDE_CODE_SESSION_ID: "abc-123" }).out, "10:00\tfrom the id");
});

// ── Codex ────────────────────────────────────────────────────────────────

const ROLL = join(CODEX, "sessions/2026/01/12");

test("codex beats a claude transcript found only by directory; --source and a Claude id override", () => {
  mkdirSync(ROLL, { recursive: true });
  writeFileSync(
    join(ROLL, "rollout-a.jsonl"),
    jsonl([
      { timestamp: "2026-01-12T11:00:00.000Z", type: "session_meta", payload: { id: "x", cwd: W } },
      {
        timestamp: "2026-01-12T11:00:01.000Z",
        type: "response_item",
        payload: {
          type: "message",
          role: "user",
          content: [{ type: "input_text", text: "# AGENTS.md instructions\n\n<INSTRUCTIONS>rules</INSTRUCTIONS>" }],
        },
      },
      {
        timestamp: "2026-01-12T11:00:02.000Z",
        type: "response_item",
        payload: { type: "message", role: "user", content: [{ type: "input_text", text: "Ship the sync engine." }] },
      },
      {
        timestamp: "2026-01-12T11:00:02.000Z",
        type: "event_msg",
        payload: { type: "user_message", message: "Ship the sync engine." },
      },
      {
        timestamp: "2026-01-12T11:05:00.000Z",
        type: "event_msg",
        payload: {
          type: "item_completed",
          item: { type: "UserMessage", content: [{ type: "text", text: "That is the wrong table." }] },
        },
      },
    ]),
  );
  writeFileSync(
    join(ROLL, "rollout-b.jsonl"),
    jsonl([
      { timestamp: "2026-01-12T12:00:00.000Z", type: "session_meta", payload: { id: "y", cwd: "/some/other/repo" } },
      { timestamp: "2026-01-12T12:00:02.000Z", type: "event_msg", payload: { type: "user_message", message: "not this session" } },
    ]),
  );
  assert.equal(run().out, "11:00\tShip the sync engine.\n11:05\tThat is the wrong table.");
  assert.equal(run(["--source", "claude"]).out.split("\n")[0], "09:00\tAdd a retry to checkout.", "--source claude forces the other record");
  assert.equal(run([], { CLAUDE_CODE_SESSION_ID: "abc-123" }).out, "10:00\tfrom the id", "…but a Claude session id wins over codex");
});

test("codex: the newest matching rollout; the session's own id picks its rollout", () => {
  const c = join(ROLL, "rollout-c.jsonl");
  writeFileSync(
    c,
    jsonl([
      { timestamp: "2026-01-12T13:00:00.000Z", type: "session_meta", payload: { id: "z", cwd: W } },
      {
        timestamp: "2026-01-12T13:00:01.000Z",
        type: "response_item",
        payload: { type: "message", role: "user", content: [{ type: "input_text", text: "<environment_context>cwd</environment_context>" }] },
      },
      {
        timestamp: "2026-01-12T13:00:02.000Z",
        type: "response_item",
        payload: { type: "message", role: "user", content: [{ type: "input_text", text: "Older format, no events." }] },
      },
    ]),
  );
  // Newer than rollout-a by a clear margin, without sleeping.
  const later = new Date(Date.now() + 5_000);
  utimesSync(c, later, later);
  assert.equal(run().out, "13:00\tOlder format, no events.", "the newest matching rollout, older format read from response items");
  assert.equal(
    run([], { CODEX_THREAD_ID: "x" }).out,
    "11:00\tShip the sync engine.\n11:05\tThat is the wrong table.",
    "the session's own id picks its rollout over a newer one in the same tree",
  );
  assert.equal(
    run([], { CODEX_SESSION_ID: "x" }).out,
    "11:00\tShip the sync engine.\n11:05\tThat is the wrong table.",
    "…CODEX_SESSION_ID too",
  );
});

test("an explicit id with no record fails, for either harness", () => {
  const cx = run([], { CODEX_THREAD_ID: "no-such-session" });
  assert.equal(cx.rc, 2, "codex: an id with no record fails, rather than reading another session's");
  assert.equal(cx.out, "", "…printing nothing");
  const cl = run([], { CLAUDE_CODE_SESSION_ID: "no-such-session" });
  assert.equal(cl.rc, 2, "claude: an id with no record fails, rather than reading the newest transcript");
  assert.equal(cl.out, "", "…printing nothing");
});

